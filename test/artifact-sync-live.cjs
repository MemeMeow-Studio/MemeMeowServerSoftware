const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const AdmZip = require('adm-zip')
const { createServer } = require('node:http')
const { once } = require('node:events')
const { getLatestSuccessfulRun, getRunArtifacts, fileDigest, extractArchive, verifyDigest, activatePublication } = require('../scripts/artifact-sync.cjs')

async function main() {
  const run = await getLatestSuccessfulRun(null)
  assert(run, 'GitHub 尚无成功构建')
  const selected = await getRunArtifacts(run, null)
  console.log(`真实 GitHub 构建：${run.id}，产物：${selected.artifacts.map(artifact => artifact.name).join(', ')}`)

  const apk = path.resolve(__dirname, '../android/app/build/outputs/apk/debug/app-debug.apk')
  const parent = path.resolve(__dirname, '../.local')
  const directory = await fs.mkdtemp(path.join(parent, 'artifact-sync-live-'))
  const archive = new AdmZip()
  archive.addLocalFile(apk)
  const zipPath = path.join(directory, 'android.zip')
  archive.writeZip(zipPath)
  const builds = path.join(directory, 'builds')
  const first = path.join(builds, 'first')
  await fs.mkdir(first, { recursive: true })
  assert.deepEqual(await extractArchive(zipPath, first), ['app-debug.apk'])
  const digest = await fileDigest(apk)
  const publishedFile = { filename: 'app-debug.apk', alias: 'MemeMeow-android.apk', sha256: digest }
  await verifyDigest(path.join(first, 'app-debug.apk'), `sha256:${digest}`)
  await fs.symlink('app-debug.apk', path.join(first, publishedFile.alias))
  await fs.writeFile(path.join(first, 'manifest.json'), JSON.stringify({ files: [publishedFile] }))
  await fs.copyFile(path.resolve(__dirname, '../mobile/www/index.html'), path.join(first, 'index.html'))
  await activatePublication(directory, 'first')
  assert.equal(await fs.readlink(path.join(directory, 'latest')), 'builds/first')

  const server = createServer(async (request, response) => {
    assert.equal(request.url, '/latest/MemeMeow-android.apk')
    response.setHeader('Content-Type', 'application/vnd.android.package-archive')
    response.end(await fs.readFile(path.join(directory, 'latest', publishedFile.alias)))
  })
  server.listen(0, '127.0.0.1')
  await once(server, 'listening')
  const downloaded = await fetch(`http://127.0.0.1:${server.address().port}/latest/MemeMeow-android.apk`)
  assert.equal(downloaded.status, 200)
  assert.deepEqual(Buffer.from(await downloaded.arrayBuffer()), await fs.readFile(apk))
  server.close()
  await once(server, 'close')

  const second = path.join(builds, 'second')
  await fs.mkdir(second)
  await fs.copyFile(apk, path.join(second, 'app-debug.apk'))
  await fs.symlink('app-debug.apk', path.join(second, publishedFile.alias))
  await fs.copyFile(path.join(first, 'manifest.json'), path.join(second, 'manifest.json'))
  await fs.copyFile(path.join(first, 'index.html'), path.join(second, 'index.html'))
  const index = path.join(directory, 'index.html')
  await fs.rm(index)
  await fs.copyFile(path.join(first, 'index.html'), index)
  await assert.rejects(activatePublication(directory, 'second'), { code: 'EINVAL' })
  assert.equal(await fs.readlink(path.join(directory, 'latest')), 'builds/first')
  await fs.rm(index)
  await fs.symlink('latest/index.html', index)
  await activatePublication(directory, 'second')
  assert.equal(await fs.readlink(path.join(directory, 'latest')), 'builds/second')
  const third = path.join(builds, 'third')
  await fs.cp(second, third, { recursive: true, verbatimSymlinks: true })
  await fs.truncate(path.join(third, 'app-debug.apk'), (await fs.stat(apk)).size - 1)
  await assert.rejects(activatePublication(directory, 'third'), /SHA-256 校验失败/)
  assert.equal(await fs.readlink(path.join(directory, 'latest')), 'builds/second')
  await fs.rm(directory, { recursive: true })
  console.log('真实 Android APK 的 ZIP 解压、完整性校验、HTTP 下载和目录切换检查通过')
}

main()
